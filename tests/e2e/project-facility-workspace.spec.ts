import { randomUUID } from 'node:crypto';
import { test, expect, consoleURL, csrf, login } from './fixtures';
import { seedResources } from '../helpers/resources';

test.use({ actionTimeout: 15_000 });

test('project facility tree searches authorized paths, pages children and preserves responsive navigation', async ({ page, request, isMobile }, info) => {
  test.setTimeout(180_000);
  const f = await seedResources(request);
  await login(page, f.user);
  const origin = new URL(consoleURL).origin;
  const api = `${origin}/api/v1/tenants/${f.tenant}`;
  const headers = { Origin: origin, 'X-CSRF-Token': await csrf(page.request, origin) };
  const post = async (path: string, data: object) => {
    const r = await page.request.post(api + path, { headers: { ...headers, 'X-Command-ID': randomUUID() }, data });
    expect(r.status(), await r.text()).toBeLessThan(300);
    return r.json();
  };
  const context = await (await page.request.get(api + '/context')).json();
  const createProject = async (code: string) => (await post('/projects', { name: code, code, purpose: '设施树验收', owner_tenant_membership_id: context.membership_id, administrator_tenant_membership_id: context.membership_id, client_request_id: randomUUID(), reason: '项目设施树验证' })).project_id as string;
  const project = await createProject('tree-project');
  const emptyProject = await createProject('empty-project');
  const root = '/engineering/resources/facilities';
  const create = (path: string, data: object) => post(path, { request_id: randomUUID(), ...data });
  const facility = await create(root, { code: 'TREE', name: '项目树桥梁', type_version_id: f.type.version_id, values: { length: 120 } });
  const retired = await create(root, { code: 'RETIRED', name: '已退役项目设施', type_version_id: f.type.version_id, values: { length: 0 } });
  const retireInput = { request_id: randomUUID(), expected_revision: 1, reason: '验证状态筛选' };
  const retirePreview = await post(`${root}/${retired.id}/mutation-preview`, { ...retireInput, action: 'retire' });
  await post(`${root}/${retired.id}/retire`, { ...retireInput, preview_hash: retirePreview.preview_hash });
  await create(root, { code: 'HIDDEN', name: '未向项目开放的设施', type_version_id: f.type.version_id, values: { length: 0 } });
  const base = `${root}/${facility.id}`;
  const component = await create(base + '/components', { code: 'SPAN', name: '主跨构件', category_key: 'span', expected_structure_revision: 1 });
  const point = await create(base + '/points', { code: 'POINT', name: '梁底测点', component_id: component.id });
  const channel = await create(base + `/points/${point.id}/channels`, { code: 'CH', name: '项目深层_目标通道', metric_version_id: f.metric.version_id, unit_version_id: f.unit.version_id, timestamp_meaning: 'observation_time' });
  await create(base + `/points/${point.id}/channels`, { code: 'HIDDEN', name: '未授权通道', metric_version_id: f.metric.version_id, unit_version_id: f.unit.version_id, timestamp_meaning: 'observation_time' });
  const grants: object[] = [{ kind: 'facility', capabilities: ['read'] }, { kind: 'component', component_id: component.id, capabilities: ['read'] }, { kind: 'point', point_id: point.id, capabilities: ['read', 'update'] }, { kind: 'channel', channel_id: channel.id, capabilities: ['read'] }];
  const rootPoints: string[] = [];
  for (let i = 0; i < 27; i++) {
    const child = await create(base + '/points', { code: `P${i}`, name: `直属测点${String(i).padStart(2, '0')}` });
    rootPoints.push(child.id);
    grants.push({ kind: 'point', point_id: child.id, capabilities: ['read'] });
  }
  const grant = async (id: string, add: object[]) => {
    const path = `/projects/${project}/resource-access/facilities/${id}`;
    const current = await (await page.request.get(api + path)).json();
    const input = { request_id: randomUUID(), reason: '设施树授权', action: 'create_link', expected_access_revision: current.policy.revision, add };
    const preview = await post(path + '/preview', input);
    await post(path + '/changes', { ...input, preview_hash: preview.preview_hash });
  };
  await grant(facility.id, grants);
  await grant(retired.id, [{ kind: 'facility', capabilities: ['read'] }]);
  const errors: string[] = [], tenantRequests: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (new URL(r.url()).pathname.startsWith(`/api/v1/tenants/${f.tenant}/engineering/resources`)) tenantRequests.push(new URL(r.url()).pathname); });
  const url = `${consoleURL}/t/${f.tenant}/p/${project}/resources/facilities`;
  await page.goto(url);
  await expect(page.getByRole('heading', { name: '项目设施', exact: true })).toBeVisible();
  const tree = page.getByRole('tree', { name: '设施、构件、测点与通道' });
  await expect(tree.getByRole('treeitem', { name: '项目树桥梁，设施', exact: true })).toBeVisible();
  await expect(tree.getByRole('treeitem', { name: '未向项目开放的设施，设施', exact: true })).toHaveCount(0);
  await page.getByLabel('搜索设施、构件、断面、孔位、测点或通道', { exact: true }).fill('_目标');
  await expect(tree.getByRole('treeitem')).toHaveCount(4);
  await tree.getByRole('treeitem', { name: '项目深层_目标通道，业务通道', exact: true }).press('Enter');
  await expect(page.getByRole('heading', { name: '项目深层_目标通道', exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('channel')).toBe(channel.id);
  await page.reload();
  const breadcrumb = page.getByRole('navigation', { name: '当前资源路径' });
  await expect(breadcrumb.getByRole('button')).toHaveCount(4);
  await breadcrumb.getByRole('button', { name: '梁底测点', exact: true }).click();
  await expect(page.getByRole('button', { name: '编辑资料', exact: true })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('heading', { name: '项目深层_目标通道', exact: true })).toBeVisible();
  await page.goForward();
  await expect(page.getByRole('heading', { name: '梁底测点', exact: true })).toBeVisible();
  const directory = async () => { if (isMobile) await page.getByRole('button', { name: '返回资源目录', exact: true }).click(); };
  await directory();
  await expect(page.getByLabel('搜索设施、构件、断面、孔位、测点或通道', { exact: true })).toHaveValue('_目标');
  await page.getByRole('button', { name: '重置筛选', exact: true }).click();
  await page.getByRole('button', { name: '收起全部资源', exact: true }).click();
  await page.getByRole('button', { name: '定位当前资源', exact: true }).click();
  await expect(tree.getByRole('treeitem', { name: '梁底测点，测点', exact: true })).toBeFocused();
  await expect(tree.getByRole('treeitem', { name: '未授权通道，业务通道', exact: true })).toHaveCount(0);
  await page.goto(`${url}/${facility.id}?tab=components`);
  await expect(page.getByRole('tab', { name: '下级资源', exact: true })).toHaveAttribute('data-state', 'active');
  await expect(page.getByText('已显示 25 / 28 项', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '加载更多下级资源', exact: true }).click();
  await expect(page.getByText('已显示 28 / 28 项', { exact: true })).toBeVisible();
  await page.goto(`${url}/${facility.id}?point=${rootPoints.at(-1)}`);
  await expect(page.getByRole('heading', { name: '直属测点26', exact: true })).toBeVisible();
  await directory();
  await expect(tree.getByRole('treeitem', { name: '直属测点26，测点', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: '设施状态', exact: true }).click();
  await expect(page.getByRole('menuitemradio', { name: '已删除记录', exact: true })).toHaveCount(0);
  await page.getByRole('menuitemradio', { name: '已退役', exact: true }).click();
  await expect(tree.getByRole('treeitem')).toHaveCount(1);
  await expect(tree.getByRole('treeitem', { name: '已退役项目设施，设施', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '重置筛选', exact: true }).click();
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => document.documentElement.classList.toggle('dark', theme === 'dark'), theme);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`project-facilities-${theme}.png`), fullPage: true });
  }
  const archive = `/projects/${project}/archive`;
  const preview = await post(archive + '/preview', {});
  await post(archive, { expected_version: preview.expected_version, expected_project_version: preview.expected_project_version, preview_hash: preview.preview_hash, reason: '验证项目归档只读', client_request_id: randomUUID() });
  await page.goto(`${url}/${facility.id}?point=${point.id}`);
  await expect(page.getByRole('heading', { name: '梁底测点', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '编辑资料', exact: true })).toHaveCount(0);
  await expect(page.getByText(/项目已归档：/)).toBeVisible();
  await page.goto(`${consoleURL}/t/${f.tenant}/p/${emptyProject}/resources/facilities`);
  await expect(page.getByText('当前项目暂无可用设施', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: '梁底测点', exact: true })).toHaveCount(0);
  expect(tenantRequests).toEqual([]);
  expect(errors).toEqual([]);
});
