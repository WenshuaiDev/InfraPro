import { randomUUID } from 'node:crypto';
import { test, expect, consoleURL, csrf, login, password } from './fixtures';
import { seedResources } from '../helpers/resources';

test('author a multi-unit metric, browse its specifications and adopt a fixed channel unit', async ({ page, request, browser }, info) => {
  test.setTimeout(120_000);
  const f = await seedResources(request);
  const code = 'multi_' + f.suffix;
  const name = '横向位移 ' + f.suffix;
  const category = 'len_' + f.suffix;
  const cm = await f.publish('units', 'cm_' + f.suffix, { name: '厘米', unit: { category, symbol: 'cm' } });
  const meter = await f.publish('units', 'meter_' + f.suffix, { name: '米', unit: { category, symbol: 'm' } });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, { username: 'e2e_owner', password });
  await page.goto(consoleURL + '/platform/engineering/metrics');
  await expect(page.getByRole('button', { name: /单位类别|类别管理/ })).toHaveCount(0);
  await page.getByRole('button', { name: '新建指标' }).click();
  const drawer = page.getByRole('dialog');
  await drawer.getByLabel('稳定编号', { exact: true }).fill(code);
  await drawer.getByLabel('定义名称', { exact: true }).fill(name);
  await drawer.getByLabel('桥梁', { exact: true }).check();
  const findUnit = drawer.getByLabel('搜索单位名称、符号或编号', { exact: true });
  await findUnit.fill('mm_' + f.suffix);
  await drawer.getByRole('button', { name: '关联毫米 V1' }).click();
  await findUnit.fill('cm_' + f.suffix);
  await drawer.getByRole('button', { name: '关联厘米 V1' }).click();
  await drawer.getByRole('button', { name: '将厘米设为标准单位' }).click();
  await drawer.getByLabel('创建原因').fill('双单位位移验证');
  await drawer.getByRole('button', { name: '创建草稿', exact: true }).click();
  await expect(drawer.getByRole('heading', { name: '当前草稿' })).toBeVisible();
  await drawer.getByRole('button', { name: /取值规则与允许单位/ }).click();
  await expect(drawer.getByRole('button', { name: '移除厘米' })).toBeDisabled();
  await drawer.getByRole('button', { name: '校验草稿' }).click();
  await expect(drawer.getByText('定义校验通过。')).toBeVisible();
  await drawer.getByRole('button', { name: '发布草稿' }).click();
  await drawer.getByLabel('本次变更原因').fill('发布两种记录单位');
  const published = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/publish'));
  await drawer.getByRole('button', { name: '确认发布 V1' }).click();
  const response = await published;
  expect(response.status(), await response.text()).toBe(200);
  const version = await response.json();
  await expect(drawer.getByRole('heading', { name: '已发布版本 V1' })).toBeVisible();
  await drawer.getByRole('button', { name: /^关闭(面板)?$/ }).click();
  const specs = page.locator('.met-sheet');
  await expect(specs).toContainText('厘米（cm）· V1');
  await expect(specs).toContainText('毫米（mm）· V1');
  await page.getByRole('button', { name: '试填样例' }).click();
  await expect(drawer.getByRole('button', { name: '验证样例与定义' })).toBeDisabled();
  await drawer.getByLabel(/观测值样例/).fill('12.5');
  await drawer.getByLabel('样例单位').selectOption(f.unit.version_id);
  await drawer.getByRole('button', { name: '验证样例与定义' }).click();
  await expect(drawer.getByText(/服务端校验通过/)).toBeVisible();
  await drawer.getByLabel('样例单位').selectOption(cm.version_id);
  await expect(drawer.getByText(/服务端校验通过/)).toHaveCount(0);
  await drawer.getByRole('button', { name: /^关闭(面板)?$/ }).click();
  await page.getByRole('button', { name: '返回目录' }).click();
  if (info.project.name === 'mobile') await page.getByLabel('浏览设施').selectOption('桥梁');
  else await page.getByRole('navigation', { name: '设施索引' }).getByRole('button', { name: /^桥梁/ }).click();
  await page.getByLabel('搜索指标名称或编号').fill(code);
  await page.getByRole('button', { name, exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await page.getByRole('button', { name: '返回目录' }).click();
  await expect(page.getByLabel('搜索指标名称或编号')).toHaveValue(code);
  await expect(page.getByRole('heading', { name: /桥梁指标/ })).toBeVisible();

  const userContext = await browser.newContext({ viewport: page.viewportSize() });
  try {
    const tenant = await userContext.newPage();
    await login(tenant, f.user);
    const origin = new URL(consoleURL).origin;
    const base = origin + '/api/v1/tenants/' + f.tenant + '/engineering/resources/facilities';
    const headers = { Origin: origin, 'X-CSRF-Token': await csrf(tenant.request, origin) };
    const create = async (path: string, data: object) => {
      const r = await tenant.request.post(path, { headers, data: { ...data, request_id: randomUUID() } });
      expect(r.status(), await r.text()).toBe(201); return r.json();
    };
    const site = await create(base, { code: 'SITE', name: '测试桥', type_version_id: f.type.version_id, values: { length: 10 } });
    const point = await create(base + '/' + site.id + '/points', { code: 'POINT', name: '观测点' });
    await tenant.goto(consoleURL + '/t/' + f.tenant + '/resources/facilities/' + site.id + '?point=' + point.id);
    await tenant.getByRole('button', { name: '新增业务通道', exact: true }).click();
    const pickMetric = async (key: string, id: string, versionId: string) => {
      await tenant.getByLabel('监测指标搜索', { exact: true }).fill(key);
      await tenant.getByLabel('监测指标定义', { exact: true }).selectOption(id);
      await tenant.getByLabel('监测指标版本', { exact: true }).selectOption(versionId);
    };
    await pickMetric(code, version.definition_id, version.version_id);
    const fixed = tenant.getByLabel('固定单位 *', { exact: true });
    await expect(fixed).toHaveValue(cm.version_id);
    await expect(fixed.locator('option')).toHaveCount(3);
    await expect(fixed.locator('option').filter({hasText: '米（m）'})).toHaveCount(0);
    await pickMetric('enum_' + f.suffix, f.enumMetric.definition_id, f.enumMetric.version_id);
    await expect(fixed).toHaveCount(0);
    await pickMetric(code, version.definition_id, version.version_id);
    await fixed.selectOption(f.unit.version_id);
    await tenant.getByLabel('编号 *', { exact: true }).fill('CHANNEL');
    await tenant.getByLabel('名称 *', { exact: true }).fill('毫米位移');
    const saved = tenant.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/channels'));
    await tenant.getByRole('button', { name: '保存', exact: true }).click();
    const channel = await saved; expect(channel.status(), await channel.text()).toBe(201);
    await expect(tenant.getByText(/固定单位：毫米/)).toBeVisible();
    const path = base + '/' + site.id + '/points/' + point.id + '/channels';
    const injected = await tenant.request.post(path, { headers, data: { request_id: randomUUID(), code: 'DISALLOWED', name: '错误单位', metric_version_id: version.version_id, unit_version_id: meter.version_id, timestamp_meaning: 'observation_time' } });
    expect(injected.status()).toBe(422);
    expect((await injected.json()).issues).toContainEqual(expect.objectContaining({ code: 'metric_unit_mismatch' }));

    await tenant.goto(consoleURL + '/t/' + f.tenant + '/monitoring/derived-definitions?id=new');
    await tenant.getByRole('navigation', { name: '指标定义编辑步骤' }).getByRole('button', { name: /输入要求/ }).click();
    await tenant.getByRole('button', { name: '设置要求', exact: true }).first().click();
    const inputs = tenant.getByRole('dialog').last();
    await inputs.getByLabel('限定公共指标（可选）搜索', { exact: true }).fill(code);
    await inputs.getByLabel('限定公共指标（可选）定义', { exact: true }).selectOption(version.definition_id);
    await inputs.getByLabel('限定公共指标（可选）版本', { exact: true }).selectOption(version.version_id);
    const constrained = inputs.getByLabel('固定单位版本', { exact: true });
    await expect(constrained).toHaveValue(cm.version_id);
    await expect(constrained.locator('option')).toHaveCount(3);
    await constrained.selectOption(f.unit.version_id);
    await expect(inputs.getByLabel('物理量', { exact: true })).toBeDisabled();
  } finally { await userContext.close(); }
  expect(errors).toEqual([]);
});
