import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { isDeepStrictEqual } from "node:util";
const check = process.argv.includes("--check"),
  protocol = JSON.parse(
    readFileSync("contracts/display/v1/protocol.json", "utf8"),
  );
function output(path, value) {
  if (check) {
    const current = readFileSync(path, "utf8");
    if (path === "contracts/openapi/api.yaml" ? !isDeepStrictEqual(JSON.parse(current),JSON.parse(value)) : current !== value)
      throw Error(`Stale display contract: ${path}`);
  } else writeFileSync(path, value);
}
const methods = protocol["x-method-capabilities"],
  events = protocol.$defs.EventKind.enum;
output(
  "packages/ts/display-sdk/src/protocol.generated.ts",
  `// Generated by scripts/display-contract.mjs.\nexport const PROTOCOL_MAJOR = ${protocol["x-protocol-major"]} as const;\nexport type ProtocolMethod = ${Object.keys(methods).map(JSON.stringify).join(" | ")};\nexport type EventKind = ${events.map(JSON.stringify).join(" | ")};\n`,
);
let go = `// Code generated by scripts/display-contract.mjs; DO NOT EDIT.\npackage display\n\nconst ProtocolMajor = ${protocol["x-protocol-major"]}\n\ntype EventKind = string\nvar methodCapabilities = map[string]string{\n${Object.entries(
  methods,
)
  .map(([m, c]) => ` ${JSON.stringify(m)}: ${JSON.stringify(c)},`)
  .join("\n")}\n}\n`;
go = execFileSync("gofmt", [], { input: go, encoding: "utf8" });
output("packages/go/platform/display/protocol_generated.go", go);
const openapi = JSON.parse(readFileSync("contracts/openapi/api.yaml", "utf8"));
for (const key of Object.keys(openapi.paths))
  if (key.includes("/displays")) delete openapi.paths[key];
for (const [key, value] of Object.entries(protocol.$defs))
    openapi.components.schemas["Display" + key] = JSON.parse(
      JSON.stringify(value).replaceAll(
        "#/$defs/",
        "#/components/schemas/Display",
      ),
    );
const source = readFileSync(
  "packages/go/platform/access/display_catalog.go",
  "utf8",
);
const routes = [
  ...source.matchAll(
    /\{"([\w.]+)", "(GET|POST|PUT|PATCH|DELETE)", "([^"]*)", (\w+), (true|false)\}/g,
  ),
];
routes.push([null, "locate", "GET", "/api/v1/displays/:id/location"]);
for (const [, action, method, suffix] of routes) {
  const path = (
    action === "locate"
      ? suffix
      : "/api/v1/tenants/:tenant_id/projects/:project_id/displays" + suffix
  ).replace(/:(\w+)/g, "{$1}");
  const parameters = [...path.matchAll(/\{(\w+)\}/g)].map(([, name]) => ({
    name,
    in: "path",
    required: true,
    schema:
      name === "part"
        ? { type: "integer", minimum: 0, maximum: 31 }
        : { type: "string", format: "uuid" },
  }));
  const ref =
    action === "list"
      ? "List"
      : action === "detail"
        ? "Detail"
        : action === "prepare"
          ? "Preparation"
          : action === "locate"
            ? "Scope"
            : "Result";
  const op = {
    operationId: "display_" + action.replaceAll(".", "_"),
    tags: ["Displays"],
    summary: `Project display ${action}`,
    parameters,
    responses: {
      200: {
        description: "Operation completed",
        content: {
          "application/json": {
            schema: { $ref: "#/components/schemas/Display" + ref },
          },
        },
      },
      403: { description: "Current authority is insufficient" },
      409: { description: "Revision, binding or capability changed" },
      422: { description: "Invalid input" },
      429: { description: "Resource budget exceeded" },
    },
  };
  if (method !== "GET") {
    op.requestBody = {
      required: true,
      content:
        action === "upload.part"
          ? {
              "application/octet-stream": {
                schema: {
                  type: "string",
                  format: "binary",
                  maxLength: 4194304,
                },
              },
            }
          : {
              "application/json": {
                schema: { $ref: "#/components/schemas/DisplayCommand" },
              },
            },
    };
  }
  if (action === "upload.part")
    parameters.push({
      name: "X-Content-SHA256",
      in: "header",
      required: true,
      schema: { type: "string", pattern: "^[a-f0-9]{64}$" },
    });
  openapi.paths[path] ??= {};
  openapi.paths[path][method.toLowerCase()] = op;
}
output("contracts/openapi/api.yaml", JSON.stringify(openapi, null, 2) + "\n");
const runtime = {
  openapi: "3.1.0", info: {title:"InfraPro Display Runtime", version:"1.0.0"},
  servers:[{url:"http://display.infra.lan"}],
  components:{schemas:Object.fromEntries(Object.entries(protocol.$defs).map(([k,v])=>[k,JSON.parse(JSON.stringify(v).replaceAll("#/$defs/","#/components/schemas/"))]))},
  paths:{},
};
const requests={query:"Call",subscribe:"Subscribe",ack:"Ack",control:"Control",bindings:null,unsubscribe:null,bootstrap:null,renew:null,switch:null,navigation:null};
for(const [action,type] of Object.entries(requests)) {
  runtime.paths[`/runtime/{session}/${action}`]={post:{operationId:`runtime_${action}`,summary:`Trusted shell ${action}; requires current host-only HttpOnly runtime cookie`,parameters:[{name:"session",in:"path",required:true,schema:{type:"string",format:"uuid"}},{name:"X-Display-Protocol",in:"header",required:true,schema:{const:"1"}}],requestBody:{required:true,content:{"application/json":{schema:type?{$ref:`#/components/schemas/${type}`}:{type:"object"}}}},responses:{200:{description:"Authorized response",content:{"application/json":{schema:action==="query"?{$ref:"#/components/schemas/Envelope"}:{type:"object"}}}},...Object.fromEntries([401,403,404,409,422,429,503].map(status=>[status,{description:"Typed failure",content:{"application/json":{schema:{$ref:"#/components/schemas/Error"}}}}]))}}};
}
runtime.paths["/runtime/{session}/events"]={get:{operationId:"runtime_events",summary:"At-least-once SSE; application ack, generation reset, 25-second reconnect, current authority checked before delivery",parameters:[{name:"session",in:"path",required:true,schema:{type:"string",format:"uuid"}},{name:"Last-Event-ID",in:"header",schema:{type:"string"}}],responses:{200:{description:"data: SubscriptionEvent; control: status or revoked",content:{"text/event-stream":{schema:{type:"string"}}}}}}};
runtime.paths["/runtime/exchange"]={post:{operationId:"runtime_exchange",requestBody:{required:true,content:{"application/json":{schema:{$ref:"#/components/schemas/Exchange"}}}},responses:{200:{description:"One-use challenge bound exchange; sets session cookie and returns bootstrap"}}}};
output("contracts/display/v1/runtime.openapi.json",JSON.stringify(runtime,null,2)+"\n");
if (!check) mkdirSync("contracts/display/v1", { recursive: true });
console.log(
  check
    ? "Display contracts current."
    : "Generated display protocol and management contracts.",
);
