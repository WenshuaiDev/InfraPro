import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { testEnv } from './test-environment.mjs';
const fixture = resolve(process.env.INFRAPRO_E2E_FIXTURE_FILE || 'build/e2e/fixture.json');
const binary = join(dirname(fixture), 'api-test');
mkdirSync(dirname(fixture), { recursive: true });
execFileSync('go', ['test', '-c', '-o', binary, './services/api/internal/transport/http'], { stdio: 'inherit' });
const child = spawn(binary, ['-test.run=^TestE2EServer$', '-test.timeout=0'], { stdio: 'inherit', env: { ...process.env, ...testEnv, INFRAPRO_E2E_SERVER: '1', INFRAPRO_E2E_FIXTURE_FILE: fixture } });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
child.on('exit', (code) => process.exit(code ?? 1));
