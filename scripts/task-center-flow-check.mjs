import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium, expect as baseExpect } from '@playwright/test';
import { origin, readJSON } from './local-runtime.mjs';
import { taskClient } from './fixtures/tasks-acceptance.mjs';

const expect = baseExpect.configure({ timeout: 30000 });
const out = '.artifacts/task-center/list-detail';
mkdirSync(out, { recursive: true });
const login = readJSON('account.json');
const api = await taskClient(origin, login);
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [], checks = [], runs = [];
page.on('pageerror', error => errors.push(error.message));
const button = name => page.getByRole('button', { name, exact: true });
const value = (url, key) => (new URL(url).searchParams.get(key) ?? '').replaceAll('"', '');
const iso = ns => new Date(Number(BigInt(ns) / 1000000n)).toISOString();

try {
  const mine = await api.call('/tasks?mode=mine&type=analysis.run&limit=100');
  const sample = mine.items.find(task => task.scope.kind === 'tenant' && task.result_state === 'available');
  assert.ok(sample, 'Supply a local workspace with a published analysis');
  const tenant = sample.scope.tenant_id, base = '/tenants/' + tenant + '/monitoring/derived', workspace = '/t/' + tenant + '/monitoring';
  const prior = await api.call(base + '/runs/' + sample.source_ref.source_root_id);
  const seed = await api.call(base + '/analysis/artifacts/' + prior.analysis.artifact_id + '?version_id=' + prior.analysis.artifact_version_id);
  await page.goto(origin + '/login');
  await page.getByLabel('用户名', { exact: true }).fill(login.username);
  await page.getByLabel('密码', { exact: true }).fill(login.password);
  await button('登录').click();
  await page.waitForURL(url => url.pathname !== '/login');
  const groupQuery = { mode: 'mine', scope_kind: 'tenant', tenant_id: tenant };
  await page.goto(origin + workspace + '/analysis');
  await page.getByRole('link', { name: '查看本空间任务' }).click();
  await page.waitForURL(url => url.pathname === '/tasks' && value(url, 'tenant_id') === tenant);
  const summary = await api.call('/tasks/summary?' + new URLSearchParams(groupQuery));
  assert.equal(summary.counts_state, 'exact');
  await expect(page.locator('.task-counts button').first().locator('strong')).toHaveText(String(summary.total));
  await expect(page.getByRole('region', { name: '任务详情' })).toBeVisible();
  for (const name of ['监测任务','计算运行']) await expect(page.getByRole('link', { name, exact: true })).toHaveCount(0);
  checks.push('Workspace shortcut and full server count ' + summary.total);

  async function submit(label, action, width, height) {
    await page.setViewportSize({ width, height });
    await page.getByLabel('运行原因', { exact: true }).fill('任务中心本机验收 · ' + label);
    const receipt = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/derived/analysis/runs') && response.request().method() === 'POST');
    await button(action).click();
    const response = await receipt;
    assert.ok(response.ok(), 'Analysis submission returned ' + response.status());
    const run = await response.json();
    const ref = run.job.task_ref ?? await api.call('/tasks/resolve?module=derived&kind=run&source_id=' + run.id);
    const info = { task: ref.task_id, generation: ref.generation, job: run.job.id, run: run.id, artifact: run.analysis.artifact_id, version: run.analysis.artifact_version_id };
    await button('查看本次任务').click();
    await page.waitForURL(url => url.pathname === '/tasks/' + info.task && value(url, 'execution') === info.generation);
    const detail = width < 768 ? page.getByRole('dialog', { name: '任务详情' }) : page.getByRole('region', { name: '任务详情' });
    await expect(detail.getByText(info.task, { exact: true })).toBeVisible();
    await expect(detail.getByRole('button', { name:'查看结果', exact:true })).toBeVisible();
    await page.screenshot({ path: join(out, label + '-任务.png') });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const target = await api.call('/tasks/' + info.task + '/target?generation=' + info.generation + '&target_kind=result');
    assert.equal(target.kind, 'analysis_artifact_version'); assert.equal(target.id, info.artifact); assert.equal(target.parameters.version, info.version);
    await detail.getByRole('button', {name:'查看结果',exact:true}).click();
    await page.waitForURL(url => url.pathname.endsWith('/analysis/' + info.artifact) && value(url, 'version') === info.version);
    await expect(page.getByRole('heading', {name:'固定成果明细'})).toBeVisible();
    const result = await api.call(base + '/analysis/artifacts/' + info.artifact + '?version_id=' + info.version);
    assert.equal(result.version.run_id, info.run);
    await expect(page.getByText('固定成果 V' + result.version.version_no, { exact:true })).toBeVisible();
    await page.screenshot({path:join(out, label + '-成果.png')});
    runs.push({...info, rows: result.version.output_rows, number: result.version.version_no});
    checks.push(label + ' real submission → exact execution → published V' + result.version.version_no);
  }
  const search = new URLSearchParams({view:'configs', id:seed.config.config_id, from:iso(seed.version.output_range.from_ns), to:iso(seed.version.output_range.to_ns)});
  await page.goto(origin + workspace + '/analysis?' + search);
  const name = '任务中心验收 ' + new Date().toLocaleString('sv-SE');
  await page.getByLabel('成果名称', {exact:true}).fill(name);
  await submit('桌面', '运行并生成完整成果', 1440, 1000);
  await page.setViewportSize({width:390,height:844});
  await button('换时段再算').click();
  await submit('手机', '生成新的完整成果版本', 390, 844);
  assert.equal(runs[0].artifact,runs[1].artifact); assert.notEqual(runs[0].version,runs[1].version);
  await page.goto(origin + workspace + '/jobs?job=' + runs[0].job);
  await page.waitForURL(url => url.pathname === '/tasks/' + runs[0].task);
  await button('查看结果').click();
  await page.waitForURL(url => value(url,'version') === runs[0].version);
  await expect(page.getByText('固定成果 V1',{exact:true})).toBeVisible();
  checks.push('Legacy job opens V1 after V2 publication');
  await page.goto(origin + workspace + '/derived-runs?id=' + runs[1].run);
  await page.waitForURL(url => url.pathname === '/tasks/' + runs[1].task);
  await page.getByRole('dialog', {name:'任务详情'}).getByRole('button',{name:'关闭面板'}).click();
  await page.waitForURL(url => url.pathname === '/tasks');
  await page.getByLabel('检索任务',{exact:true}).fill(runs[1].task);
  await button('搜索').click();
  const item = page.locator('#task-' + runs[1].task);
  await expect(item).toBeVisible(); await item.click();
  await expect(page.getByRole('dialog').getByText(runs[1].task,{exact:true})).toBeVisible();
  checks.push('Mobile legacy run → list → search → same detail');
  const exports=await api.call('/tasks?mode=mine&type=monitoring.export&limit=100');
  const restricted=exports.items.find(t=>t.state==='succeeded' && t.result_state==='restricted');
  assert.ok(restricted,'Expected a completed export with restricted file access in the acceptance workspace');
  const denied=await api.call('/tasks/'+restricted.id+'/target?target_kind=result&generation='+restricted.generation);
  assert.equal(denied.available,false);assert.ok(!denied.id);
  await page.goto(origin+'/tasks/'+restricted.id+'?execution='+restricted.generation);
  const drawer=page.getByRole('dialog',{name:'任务详情'});
  await expect(drawer.getByText('已完成',{exact:true}).first()).toBeVisible();
  await expect(drawer.getByText('结果访问受限',{exact:true}).first()).toBeVisible();
  await expect(drawer.getByRole('button',{name:'查看结果'})).toHaveCount(0);
  checks.push('Completed export '+restricted.id+' shows restricted result and returns no target');
  assert.deepEqual(errors,[]);
  writeFileSync(join(out,'business-flow.json'),JSON.stringify({passed:true,origin,tenant,runs,checks},null,2));
  console.log(JSON.stringify({runs,checks},null,2));
} catch(error) {
  await page.screenshot({path:join(out,'flow-error.png')}).catch(()=>{});
  console.error('Failed at ' + new URL(page.url()).pathname, String(error.stack ?? error).slice(0,2200));
  process.exitCode = 1;
} finally { await api.client.dispose(); await browser.close(); }
