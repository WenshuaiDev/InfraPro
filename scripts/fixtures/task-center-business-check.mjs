import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { queueNotificationImport } from './notifications-acceptance.mjs';

export async function verifyBusinessTasks({ page, api, lab, state, expect, checks, login, logout, derivedAPI }) {
  const button = name => page.getByRole('button',{name,exact:true});
  const result = () => button('查看结果');
  await logout(); await login('A');
  const tenant = state.owner.tenants[0], project = state.owner.projects[0], workspace = '/t/'+tenant+'/monitoring';
  const search = url => new URL(url).searchParams;
  await page.goto(lab.origin+'/t/'+tenant+'/p/'+project+'/monitoring/imports');
  await page.getByRole('link',{name:'查看本空间任务',exact:true}).click();
  await page.waitForURL(url => url.pathname === '/tasks' && search(url).get('scope_kind') === 'project' && search(url).get('project_id') === project);
  const filters = new URLSearchParams({scope_kind:'project',tenant_id:tenant,project_id:project,mode:'mine'});
  const summary = await api.call('/tasks/summary?'+filters);
  let cursor = '', count = 0;
  do {
    const records = await api.call('/tasks?'+filters+'&limit=10&cursor='+encodeURIComponent(cursor));
    assert.ok(records.items.every(row => row.scope.project_id === project)); count += records.items.length;
    cursor = records.next_cursor;
  } while(cursor);
  assert.equal(summary.total,count);
  await expect(page.locator('.task-counts strong').first()).toHaveText(String(count));
  await page.getByRole('tab',{name:'管理视图'}).click();
  await expect.poll(()=>search(page.url()).get('mode')).toBe('managed');
  await button('任务类型').click();
  const option = page.getByRole('menuitemcheckbox').first();
  const selectedName = await option.innerText(); await option.click(); await page.keyboard.press('Escape');
  await expect.poll(()=>search(page.url()).get('type')).toBeTruthy();
  const code = search(page.url()).get('type');
  const typed = await api.call('/tasks?'+new URLSearchParams({...Object.fromEntries(filters),type:code,mode:'managed'}));
  assert.ok(typed.items.every(row=>row.type===code&&row.scope.project_id===project));
  checks.push('Project shortcut, exact full-scope count, managed type filter '+selectedName);
  await page.goto(lab.origin+workspace+'/imports');
  await expect(page.getByRole('link',{name:'监测任务',exact:true})).toHaveCount(0);
  await expect(page.getByRole('link',{name:'计算运行',exact:true})).toHaveCount(0);
  const fraction=String(parseInt(randomBytes(3).toString('hex'),16)).padStart(9,'0');
  const prepared=await queueNotificationImport(api,state.owner,'本次采用回执.csv','observed_at,value,quality\n2024-01-04T00:00:00.'+fraction+'Z,21,good\n');
  await expect.poll(async()=>(await api.call('/tenants/'+tenant+'/monitoring/imports/'+prepared.batch)).state).toBe('ready');
  await page.goto(lab.origin+workspace+'/imports/'+prepared.batch);
  await button('发布合格批次').click(); await page.getByLabel('操作原因',{exact:true}).fill('验证本次采用回执');
  const accepted = page.waitForResponse(r=>r.url().includes('/imports/'+prepared.batch+'/publish') && r.request().method()==='POST');
  await button('确认发布该批次').click();
  const response=await accepted;assert.ok(response.ok());
  const receipt=await response.json();
  assert.notEqual(receipt.job_id,prepared.job);
  const ref=receipt.task_ref??await api.call('/tasks/resolve?module=monitoring&kind=job&source_id='+receipt.job_id);
  await button('查看本次任务').click();await page.waitForURL(u=>u.pathname==='/tasks/'+ref.task_id);
  await result().click();await page.waitForURL(u=>u.pathname.endsWith('/imports/'+prepared.batch) && search(u).get('job')===receipt.job_id);
  await expect(page.getByRole('heading',{name:'本次批次处理结果'})).toBeVisible();
  await expect(page.getByText(receipt.job_id,{exact:true})).toBeVisible();
  checks.push('Real import adoption → own job → same batch execution receipt');
  const derived=state.derived, root='/t/'+derived.tenant+'/monitoring', apiBase='/tenants/'+derived.tenant+'/monitoring/derived';
  await page.goto(lab.origin+'/tasks');await logout();await login('B');await page.setViewportSize({width:390,height:844});
  await page.goto(lab.origin+root+'/derived/'+derived.channels.A_MINUS_B.id);
  await button('运行管理').click();await button('试算核对').click();
  const form=button('对完整范围试算').locator('xpath=ancestor::section[1]');
  const iso=ns=>new Date(Number(BigInt(ns)/1000000n)).toISOString();
  await form.getByLabel('起点（含）',{exact:true}).fill(iso(derived.range.from_ns));
  await form.getByLabel('终点（不含）',{exact:true}).fill(iso(derived.range.to_ns));
  await form.getByLabel('操作原因',{exact:true}).fill('核对固定计算时段');
  const trialResponse=page.waitForResponse(r=>r.url().includes('/channels/'+derived.channels.A_MINUS_B.id+'/trials')&&r.request().method()==='POST');
  await button('对完整范围试算').click();
  const http=await trialResponse;assert.ok(http.ok());
  const trial=await http.json();
  await form.getByRole('button',{name:'查看本次任务',exact:true}).click();
  const reference=trial.job.task_ref??await derivedAPI.call('/tasks/resolve?module=derived&kind=run&source_id='+trial.id);
  await page.waitForURL(u=>u.pathname==='/tasks/'+reference.task_id);
  await result().click();await page.waitForURL(u=>search(u).get('id')===trial.id&&search(u).get('view')==='result');
  await expect(page.getByRole('table',{name:'计算输出与匹配解释'})).toBeVisible();
  const actual=await derivedAPI.call(apiBase+'/runs/'+trial.id);assert.ok(actual.trial.output_count!=='0');
  checks.push('Mobile real derived trial → same task → exact trial output');
  const exported=state.analysis.artifactExport;
  const fileRef=exported.job.task_ref??await derivedAPI.call('/tasks/resolve?module=derived&kind=export&source_id='+exported.id);
  await page.goto(lab.origin+'/tasks/'+fileRef.task_id+'?execution='+fileRef.generation);
  await result().click();await page.waitForURL(u=>search(u).get('export_id')===exported.id);
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:/\.csv$/i}).first().click();
  const file=await download;assert.equal(await file.failure(),null);
  checks.push('Fixed export task → same export → downloaded CSV');
}
